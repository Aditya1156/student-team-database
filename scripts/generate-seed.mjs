import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const extracted = path.join(root, 'docs', 'review', 'extracted');

function workbook(file) {
  let text = fs.readFileSync(path.join(extracted, file), 'utf8');
  if (text.charCodeAt(0) === 0xfeff) text = text.slice(1);
  return JSON.parse(text);
}

function sheet(book, name) {
  const value = book.sheets.find((item) => item.name === name);
  if (!value) throw new Error(`Missing sheet: ${name}`);
  return value.rows.map((row) => ({
    row: row.row,
    ...Object.fromEntries(row.cells.map((cell) => [cell.address.replace(/[0-9]/g, ''), cell.value]))
  }));
}

const q = (value) => value == null ? 'null' : `'${String(value).replaceAll("'", "''")}'`;
const slug = (value, prefix) => `${prefix}-${String(value).normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`;
const code = (value) => String(value).normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
const title = (value) => String(value).split('_').map((part) => part ? part[0].toUpperCase() + part.slice(1) : part).join(' ');

const thanushree = workbook('Thanushree_kh_Data_Dictionary.json');
const prajwal = workbook('Prajwal_Data_Dictionary_Final (2).json');
const tejaswini = workbook('Tejaswini_safety_value_list.json');
const mahera = workbook('Mahera_Data_Dictionary_FinalLast5.json');

const interestRows = sheet(thanushree, 'Interest Catalog').filter((row) => /^\d+$/.test(String(row.A ?? '')) && row.B && row.C && row.D && row.E);
const categoryOrder = [...new Set(interestRows.map((row) => row.B))];
const subcategories = [];
const seenSubcategories = new Set();
for (const row of interestRows) {
  const key = `${row.B}\u0000${row.C}`;
  if (!seenSubcategories.has(key)) {
    seenSubcategories.add(key);
    subcategories.push({ category: row.B, name: row.C });
  }
}

const promptRows = sheet(thanushree, 'All Values').filter((row) => row.B === 'core.prompt_catalogue' && row.C === 'Prompt' && row.F && row.G);
const intentRows = sheet(prajwal, 'Seed Intents').filter((row) => /^int_\d{3}$/.test(String(row.B ?? '')));
const taxonomyRows = sheet(tejaswini, 'Approved Taxonomy').filter((row) => /^\d+$/.test(String(row.A ?? '')) && row.B && row.C);

const maheraValues = sheet(mahera, 'Value Lists');
function controlledValues(tableName, columnName) {
  let currentTable = '';
  let currentColumn = '';
  const values = [];
  for (const row of maheraValues) {
    if (typeof row.A === 'string' && row.A.startsWith('core.')) currentTable = row.A.split(/\s+\|/)[0].trim();
    if (row.A && row.B && row.B !== '\u21b3') currentColumn = String(row.B).trim();
    if (currentTable === tableName && currentColumn === columnName && row.B === '\u21b3' && row.C) values.push(row);
  }
  return values;
}

const notificationRows = controlledValues('core.notification_category_preferences', 'category');
const closeReasonRows = controlledValues('core.connections', 'closed_reason');
if (interestRows.length !== 962 || promptRows.length !== 100 || intentRows.length !== 110 || taxonomyRows.length !== 219 || notificationRows.length !== 38 || closeReasonRows.length !== 41) {
  throw new Error(JSON.stringify({ interests: interestRows.length, prompts: promptRows.length, intents: intentRows.length, taxonomy: taxonomyRows.length, notifications: notificationRows.length, closeReasons: closeReasonRows.length }));
}

const sql = [];
sql.push('-- Generated by scripts/generate-seed.mjs from the eight reviewed workbooks.');
sql.push('-- Re-run the generator after changing a source workbook; do not hand-edit catalog rows.');
sql.push('begin;');

categoryOrder.forEach((name, index) => {
  sql.push(`insert into core.interest_categories (name, slug, display_order) values (${q(name)}, ${q(slug(name, 'cat'))}, ${index + 1}) on conflict (slug) do update set name = excluded.name, display_order = excluded.display_order;`);
});
subcategories.forEach((item, index) => {
  sql.push(`insert into core.interest_subcategories (category_id, name, slug, display_order) select id, ${q(item.name)}, ${q(slug(`${item.category}-${item.name}`, 'sub'))}, ${index + 1} from core.interest_categories where slug = ${q(slug(item.category, 'cat'))} on conflict (slug) do update set name = excluded.name, display_order = excluded.display_order;`);
});
interestRows.forEach((row, index) => {
  sql.push(`insert into core.interests (subcategory_id, label, slug, intent, status, display_order) select id, ${q(row.D)}, ${q(row.E)}, ${q(row.F ?? null)}, ${q(row.G === 'deprecated' ? 'deprecated' : 'active')}, ${index + 1} from core.interest_subcategories where slug = ${q(slug(`${row.B}-${row.C}`, 'sub'))} on conflict (slug) do update set label = excluded.label, intent = excluded.intent, status = excluded.status, display_order = excluded.display_order;`);
});

promptRows.forEach((row, index) => {
  let promptCode = code(row.F);
  if (promptCode.length > 60) promptCode = `prompt_${String(index + 1).padStart(3, '0')}`;
  sql.push(`insert into core.prompt_catalogue (prompt_code, prompt_text, display_order) values (${q(promptCode)}, ${q(row.G)}, ${index + 1}) on conflict (prompt_code) do update set prompt_text = excluded.prompt_text, display_order = excluded.display_order;`);
});

intentRows.forEach((row) => {
  sql.push(`insert into core.connection_intents (intent_id, intent_code, display_label, category, sort_order, status) values (${q(row.B)}, ${q(row.D)}, ${q(row.E)}, ${q(row.C)}, ${Number(row.F)}, ${q(row.G === 'inactive' ? 'inactive' : 'active')}) on conflict (intent_code) do update set display_label = excluded.display_label, category = excluded.category, sort_order = excluded.sort_order, status = excluded.status;`);
});

taxonomyRows.forEach((row) => {
  sql.push(`insert into safety.report_category_subcategories (category, subcategory, display_label) values (${q(row.B)}, ${q(row.C)}, ${q(title(row.C))}) on conflict (category, subcategory) do update set display_label = excluded.display_label;`);
});

notificationRows.forEach((row) => {
  const notes = String(row.E ?? '');
  const mandatory = /^Mandatory/i.test(notes);
  const marketing = /consent/i.test(notes) || row.C === 'newsletter_marketing';
  const priority = /critical/i.test(notes) ? 'critical' : /high/i.test(notes) ? 'high' : 'normal';
  sql.push(`insert into core.notification_categories (category_code, display_label, description, default_priority, is_mandatory, requires_marketing_consent) values (${q(row.C)}, ${q(title(row.C))}, ${q(row.D)}, ${q(priority)}, ${mandatory}, ${marketing}) on conflict (category_code) do update set display_label = excluded.display_label, description = excluded.description, default_priority = excluded.default_priority, is_mandatory = excluded.is_mandatory, requires_marketing_consent = excluded.requires_marketing_consent;`);
  const match = notes.match(/channels:\s*([^;]+)/i);
  for (const channel of (match?.[1] ?? 'in_app').split(',').map((value) => value.trim()).filter((value) => ['in_app', 'push', 'email'].includes(value))) {
    sql.push(`insert into core.notification_category_channels (channel, category_code) values (${q(channel)}, ${q(row.C)}) on conflict do nothing;`);
  }
});

closeReasonRows.forEach((row) => {
  const actor = String(row.E ?? '').match(/closed_by_type\s*=\s*(user|admin|system)/i)?.[1] ?? 'system';
  const visible = actor === 'user' && !/never shown|internal|security|moderation/i.test(String(row.E ?? ''));
  sql.push(`insert into core.connection_closed_reasons (code, closed_by_type, description, is_user_visible) values (${q(row.C)}, ${q(actor)}, ${q(row.D)}, ${visible}) on conflict (code, closed_by_type) do update set description = excluded.description, is_user_visible = excluded.is_user_visible;`);
});

sql.push('commit;');
sql.push('');
fs.writeFileSync(path.join(root, 'supabase', 'seed.sql'), sql.join('\n'), 'utf8');
console.log(JSON.stringify({ categories: categoryOrder.length, subcategories: subcategories.length, interests: interestRows.length, prompts: promptRows.length, intents: intentRows.length, taxonomy: taxonomyRows.length, notifications: notificationRows.length, closeReasons: closeReasonRows.length }, null, 2));
