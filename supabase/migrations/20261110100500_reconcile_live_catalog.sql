-- Reconcile objects that existed in the cloud project before they were captured
-- in version-controlled migrations. This migration is intentionally idempotent:
-- it is safe on the existing project and creates the same catalog on a clean DB.

create table if not exists core.connection_modes (
  mode_code text primary key,
  display_label text not null,
  rollout_status text not null,
  is_initial_candidate boolean not null default false,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  constraint connection_modes_rollout_status_check check (
    rollout_status in ('candidate','review_required','active','inactive')
  ),
  constraint connection_modes_check check (
    not is_initial_candidate or rollout_status = 'candidate'
  )
);

create table if not exists core.connection_mode_intents (
  mode_code text not null,
  intent_code varchar not null,
  primary key (mode_code, intent_code),
  constraint connection_mode_intents_mode_code_fkey
    foreign key (mode_code) references core.connection_modes(mode_code),
  constraint connection_mode_intents_intent_code_fkey
    foreign key (intent_code) references core.connection_intents(intent_code)
);

create table if not exists safety.legal_hold_evidence (
  id bigint generated by default as identity primary key,
  legal_hold_id bigint not null,
  evidence_id bigint not null,
  created_at timestamptz not null default clock_timestamp(),
  constraint legal_hold_evidence_legal_hold_id_evidence_id_key
    unique (legal_hold_id, evidence_id),
  constraint legal_hold_evidence_legal_hold_id_fkey
    foreign key (legal_hold_id) references safety.legal_holds(id) on delete restrict,
  constraint legal_hold_evidence_evidence_id_fkey
    foreign key (evidence_id) references safety.report_evidence(id) on delete restrict
);

create index if not exists legal_hold_evidence_hold_ix
  on safety.legal_hold_evidence(legal_hold_id);
create index if not exists legal_hold_evidence_evidence_ix
  on safety.legal_hold_evidence(evidence_id);

create table if not exists safety.evidence_storage_deletion_jobs (
  id bigint generated by default as identity primary key,
  evidence_id bigint not null,
  storage_bucket varchar(100) not null,
  storage_object_key text not null,
  status varchar(20) not null default 'pending',
  attempt_count integer not null default 0,
  next_attempt_at timestamptz not null default clock_timestamp(),
  worker_id text,
  lease_expires_at timestamptz,
  last_error_code text,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  completed_at timestamptz,
  dead_lettered_at timestamptz,
  constraint evidence_storage_deletion_jobs_evidence_id_fkey
    foreign key (evidence_id) references safety.report_evidence(id) on delete restrict,
  constraint evidence_storage_deletion_status_ck check (
    status in ('pending','processing','retry_wait','completed','dead_letter')
  ),
  constraint evidence_storage_deletion_attempt_ck check (attempt_count >= 0),
  constraint evidence_storage_deletion_object_ck check (
    length(btrim(storage_bucket)) > 0 and length(btrim(storage_object_key)) > 0
  ),
  constraint evidence_storage_deletion_lease_ck check (
    (status = 'processing' and worker_id is not null and lease_expires_at is not null)
    or (status <> 'processing' and worker_id is null and lease_expires_at is null)
  ),
  constraint evidence_storage_deletion_completed_ck check (
    (status = 'completed' and completed_at is not null)
    or (status <> 'completed' and completed_at is null)
  ),
  constraint evidence_storage_deletion_dead_letter_ck check (
    (status = 'dead_letter' and dead_lettered_at is not null)
    or (status <> 'dead_letter' and dead_lettered_at is null)
  )
);

create unique index if not exists evidence_storage_deletion_evidence_uq
  on safety.evidence_storage_deletion_jobs(evidence_id);
create index if not exists evidence_storage_deletion_pending_ix
  on safety.evidence_storage_deletion_jobs(next_attempt_at, created_at)
  where status in ('pending','retry_wait');
create index if not exists evidence_storage_deletion_lease_ix
  on safety.evidence_storage_deletion_jobs(lease_expires_at)
  where status = 'processing';

-- The live application uses one normalized display location. Convert the older
-- city/state/country representation without losing existing values.
alter table core.profiles add column if not exists location varchar(255);

do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'core' and table_name = 'profiles' and column_name = 'city'
  ) then
    execute $sql$
      update core.profiles
      set location = coalesce(
        nullif(concat_ws(', ', nullif(city, ''), nullif(state, ''), nullif(country, '')), ''),
        '[unspecified]'
      )
      where location is null
    $sql$;
  else
    update core.profiles set location = '[unspecified]' where location is null;
  end if;
end;
$$;

update core.profiles set bio = '' where bio is null;

drop index if exists core.profiles_discovery_ix;

alter table core.profiles
  alter column location set not null,
  alter column bio set not null,
  drop column if exists city,
  drop column if exists state,
  drop column if exists country;

alter table core.profiles drop constraint if exists profiles_user_id_fkey;
alter table core.profiles
  add constraint profiles_user_id_fkey
  foreign key (user_id) references core.users(user_id) on delete cascade;

create index if not exists profiles_discovery_ix
  on core.profiles(visibility_status, location)
  where deleted_at is null;

comment on table core.connection_modes is
  'Version-controlled reconciliation of the connection mode catalogue.';
comment on table safety.evidence_storage_deletion_jobs is
  'Durable worker queue for deleting external evidence objects during controlled erasure.';
